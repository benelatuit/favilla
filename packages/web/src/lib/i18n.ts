export type Lang = Language;

/** The setting ('auto' or a language), auto taking the first of the browser's languages that the interface has. */
export function resolveLang(setting: string | undefined): Lang {
  if (setting !== 'auto' && isLanguage(setting)) return setting;
  const wanted = typeof navigator === 'undefined' ? [] : navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const locale of wanted) {
    const lang = languageForLocale(locale);
    if (lang) return lang;
  }
  return 'en';
}

/** An installed extension's word, from what the server said of it (its cards' and settings' text). */
function extensionWord(lang: Lang, key: string): string | undefined {
  for (const e of getState().info?.extensions ?? []) {
    const s = e.strings[lang]?.[key];
    if (s !== undefined) return s;
  }
  return undefined;
}

/**
 * The page's words by language. Chinese comes with the page; the others are fetched when first wanted, so a
 * language nobody uses costs nothing, and until its table is here its words show in English.
 */
const tables = new Map<Lang, Record<string, string>>([['zh-CN', zh]]);
const sources = import.meta.glob<{ default: Record<string, string> }>('../locales/*.ts');
const loading = new Map<Lang, Promise<void>>();
const listeners = new Set<() => void>();

export function loadLanguage(lang: Lang): Promise<void> {
  if (lang === 'en' || tables.has(lang)) return Promise.resolve();
  let p = loading.get(lang);
  if (!p) {
    const source = sources[`../locales/${lang}.ts`];
    p = (source ? source() : Promise.resolve({ default: {} }))
      .then((m) => {
        tables.set(lang, m.default);
        for (const l of listeners) l();
      })
      .catch(() => {
        // Tried again the next time it is wanted; meanwhile its words show in English.
        loading.delete(lang);
      });
    loading.set(lang, p);
  }
  const fallback = FALLBACK[lang];
  return fallback ? Promise.all([p, loadLanguage(fallback)]).then(() => undefined) : p;
}

function word(lang: Lang, key: string): string | undefined {
  return tables.get(lang)?.[key] ?? coreWords[lang]?.[key] ?? extensionWord(lang, key);
}

export function translate(lang: Lang, key: string): string {
  if (lang === 'en') return key;
  const fallback = FALLBACK[lang];
  return word(lang, key) ?? (fallback ? word(fallback, key) : undefined) ?? key;
}

/** Put a count into a translated template: fill(t('read {n} files'), 3). */
export function fill(template: string, n: number | string): string {
  return template.replace('{n}', String(n));
}

/** A count in words, the singular key for one: count(t, 1, '{n} file', '{n} files') is "1 file", not "1 files". */
export function count(t: (key: string) => string, n: number, one: string, many: string): string {
  return fill(t(n === 1 ? one : many), n);
}

/**
 * One translator per language: a component or effect that takes `t` gets the same function from render to render,
 * where a new one each time redid every memo and listener that named it. A language whose table has just arrived
 * gets a new one, so what was drawn in English while it came is drawn again.
 */
const translators = new Map<string, (key: string) => string>();

function subscribe(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function useT(): (key: string) => string {
  const lang = useStore((s) => resolveLang(s.info?.config.language));
  const ready = useSyncExternalStore(subscribe, () => lang === 'en' || tables.has(lang));
  useEffect(() => {
    void loadLanguage(lang);
  }, [lang]);
  const id = ready ? lang : `${lang}~`;
  let t = translators.get(id);
  if (!t) translators.set(id, (t = (key: string) => translate(lang, key)));
  return t;
}
